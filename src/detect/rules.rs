//! Component phrases (as MSRC titles and tags word them) → binaries.
//! Phrases are matched on normalized text (lower-case words); the first
//! binary of a rule is the most likely one.

pub struct Rule {
    pub phrases: &'static [&'static str],
    pub binaries: &'static [&'static str],
    /// Base score when the phrase appears in the title or tag.
    pub weight: u8,
}

macro_rules! rule {
    ($w:expr, [$($p:expr),+ $(,)?] => [$($b:expr),+ $(,)?]) => {
        Rule { phrases: &[$($p),+], binaries: &[$($b),+], weight: $w }
    };
}

